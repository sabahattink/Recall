import type { ProjectMemory } from '@recall-ai/schemas';
import type { AgentTemplate } from '../template.js';
import { document, section } from '../markdown.js';
import {
  architectureLines,
  conventionLines,
  dependencyLines,
  descriptionLines,
  installLines,
  labeledStructureLines,
  projectTitle,
  provenanceLines,
  riskLines,
  scriptLines,
  stackLines,
} from '../sections.js';

const NO_CITE = { cite: false };

/**
 * Cursor project-rule front matter. The description is emitted as a JSON
 * string, which is also a valid YAML double-quoted scalar, so any project
 * name is quoted safely.
 */
function frontMatter(memory: ProjectMemory): string[] {
  const name = memory.metadata.name?.value ?? 'this repository';
  return [
    '---',
    `description: ${JSON.stringify(`Project memory for ${name}, generated by Recall`)}`,
    'alwaysApply: true',
    '---',
  ];
}

/**
 * Cursor applies project rules from `.cursor/rules/*.mdc`; this file starts
 * with rule front matter (always applied) so it can be copied there as-is.
 * Rules are injected into every request, so this rendering stays compact:
 * no evidence citations and runtime dependencies only.
 */
export const cursorTemplate: AgentTemplate = {
  id: 'cursor',
  displayName: 'Cursor',
  render: (memory) =>
    document([
      frontMatter(memory),
      [`# ${projectTitle(memory)}`],
      [
        ...provenanceLines(memory),
        '>',
        '> Copy this file to `.cursor/rules/recall.mdc` so Cursor applies it to every request.',
      ],
      section('## Stack', [...descriptionLines(memory), ...stackLines(memory, NO_CITE)]),
      section('## Commands', [...installLines(memory), ...scriptLines(memory)]),
      section('## Layout', [
        ...architectureLines(memory, NO_CITE),
        ...labeledStructureLines(memory),
      ]),
      section('## Conventions', conventionLines(memory, NO_CITE)),
      section('## Risks', riskLines(memory, NO_CITE)),
      section(
        '## Runtime dependencies',
        dependencyLines(memory, { includeDevelopment: false, maxPerGroup: 25 }),
      ),
    ]),
};
